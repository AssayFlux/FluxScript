"""Generate a standalone argparse-based CLI from an application specification."""
from pathlib import Path
from ..models import AppSpec


def generate_cli(spec: AppSpec, out: Path) -> list[Path]:
    issues = spec.validate()
    if issues: raise ValueError("Invalid application: " + "; ".join(issues))
    actions = []
    for page in spec.pages:
        for element in page.elements:
            if element.kind == "button" and element.action and element.action not in actions:
                actions.append(element.action)
    input_names = sorted({element.name for page in spec.pages for element in page.elements if element.kind == "input" and element.name})
    command_specs = []
    for index, action in enumerate(actions):
        command_specs.append(f'''    command_{index} = commands.add_parser({action!r}, help={("Request action " + action)!r})
    command_{index}.set_defaults(action_name={action!r})''')
        for name in input_names:
            command_specs.append(f'''    command_{index}.add_argument({("--" + name.replace("_", "-"))!r}, default="", help={("Value for " + name)!r})''')
    if not actions:
        command_specs.append('''    commands.add_parser("info", help="show application metadata").set_defaults(action_name="info")''')
    value_names = ", ".join(repr(name) for name in input_names)
    command_name = "".join(ch.lower() if ch.isalnum() else "-" for ch in spec.name).strip("-") or "fluxscript-app"
    source = f'''#!/usr/bin/env python3
"""Command-line interface generated by FluxScript for {spec.name!r}."""
import argparse
import json

APP_NAME = {spec.name!r}
INPUT_NAMES = [{value_names}]

def main(argv=None):
    parser = argparse.ArgumentParser(prog={command_name!r}, description=APP_NAME)
    commands = parser.add_subparsers(dest="command", required=True)
{chr(10).join(command_specs)}
    args = parser.parse_args(argv)
    values = {{name: getattr(args, name, "") for name in INPUT_NAMES}}
    print(json.dumps({{"application": APP_NAME, "action": args.action_name, "values": values}}, ensure_ascii=False))
    return 0

if __name__ == "__main__":
    raise SystemExit(main())
'''
    out.mkdir(parents=True, exist_ok=True)
    cli_file = out / "app_cli.py"
    cli_file.write_text(source, encoding="utf-8")
    readme = out / "README.md"
    readme.write_text(f"# {spec.name} command-line starter\n\nRun `python app_cli.py --help` to list generated action commands. Each command emits a JSON action request and supplied input values. Connect application-specific business logic before treating requests as completed operations.\n", encoding="utf-8")
    return [cli_file, readme]
