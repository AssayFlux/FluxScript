"""Generate a SwiftUI source starter for every declared page."""
from pathlib import Path
import json
from ..models import AppSpec

def _swift(value: str) -> str:
    # JSON string escaping is compatible with the common Swift string-literal escapes.
    return json.dumps(str(value), ensure_ascii=False)

def _identifier(name: str) -> str:
    clean = "".join(c if c.isalnum() or c == "_" else "_" for c in name)
    if not clean or clean[0].isdigit(): clean = "field_" + clean
    return "input_" + clean

def generate_ios(spec: AppSpec, out: Path) -> list[Path]:
    issues = spec.validate()
    if issues: raise ValueError("Invalid application: " + "; ".join(issues))
    input_names = sorted({e.name for page in spec.pages for e in page.elements if e.kind == "input" and e.name})
    state_lines = [f"    @State private var {_identifier(name)}: String = \"\"" for name in input_names]
    state_lines.append('    @State private var statusMessage: String = ""')
    tabs=[]
    for page in spec.pages:
        rows=[]
        for e in page.elements:
            text = _swift(e.text)
            if e.kind == "text": rows.append(f"                    Text({text}).frame(maxWidth: .infinity, alignment: .leading)")
            elif e.kind == "heading": rows.append(f"                    Text({text}).font(.system(size: {max(16, 34 - int(e.attributes.get('level', 1)) * 3)}, weight: .bold)).frame(maxWidth: .infinity, alignment: .leading)")
            elif e.kind == "button": rows.append(f"                    Button({text}) {{ statusMessage = {_swift('Action requested: ' + (e.action or ''))} }}.buttonStyle(.borderedProminent)")
            elif e.kind == "input": rows.append(f"                    TextField({text}, text: ${_identifier(e.name or 'field')}).textFieldStyle(.roundedBorder)")
        if not rows: rows.append('                    Text("Generated by FluxScript")')
        rows.append('                    if !statusMessage.isEmpty { Text(statusMessage).font(.footnote).foregroundStyle(.secondary) }')
        page_title = page.title or page.path
        tabs.append(f'''            NavigationStack {{
                ScrollView {{
                    VStack(alignment: .leading, spacing: 16) {{
{chr(10).join(rows)}
                    }}
                    .padding()
                }}
                .navigationTitle({_swift(page_title)})
            }}
            .tabItem {{ Label({_swift(page_title)}, systemImage: "doc.text") }}''')
    swift=f'''import SwiftUI

@main
struct GeneratedApp: App {{
    var body: some Scene {{
        WindowGroup {{ ContentView() }}
    }}
}}

struct ContentView: View {{
{chr(10).join(state_lines)}

    var body: some View {{
        TabView {{
{chr(10).join(tabs)}
        }}
    }}
}}
'''
    out.mkdir(parents=True, exist_ok=True)
    source = out / "GeneratedApp.swift"; source.write_text(swift, encoding="utf-8")
    readme = out / "README.md"
    readme.write_text("# Generated SwiftUI source\n\nFluxScript generates a SwiftUI source starter with a tab for each declared page and editable text fields. Create an Xcode project on macOS, add `GeneratedApp.swift`, then build and test with Xcode. This generator does not create an `.xcodeproj`, compile, sign, or create an `.ipa`. Review navigation labels, action handlers, state management, accessibility and platform deployment settings before production use.\n", encoding="utf-8")
    return [source, readme]
